export const QUESTIONS: Question[] = source.map(([heading, situation, choices], index) => {
  const number = index + 1;
  const [category, topic] = heading.split("／");
  return {
    id: questionId(number),
    number,
    category,
    topic,
    situation,
    choices,
    compareWith: comparisons[number] ?? [],
  };
});

export const TOTAL_QUESTIONS = QUESTIONS.length;

export function questionId(number: number) {
  return `q${String(number).padStart(3, "0")}`;
}

const byId = new Map(QUESTIONS.map((question) => [question.id, question]));

export function getQuestion(id: string): Question | undefined {
  return byId.get(id);
}

export function getQuestionByNumber(number: number): Question | undefined {
  return QUESTIONS[number - 1];
}

export function headingOf(question: Question) {
  return `${question.category}／${question.topic}`;
}
