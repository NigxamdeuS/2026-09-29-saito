export function isMode(value: unknown): value is Mode {
  return MODES.some((mode) => mode.key === value);
}

export function modeOf(key: Mode) {
  return MODES.find((mode) => mode.key === key)!;
}

export function nextMode(key: Mode) {
  return MODES.find((mode) => mode.tier === modeOf(key).tier + 1) ?? null;
}

export type Item = {
  id: string;
  measure: MeasureKey;
  /** 1: 当てはまるほど尺度の高い側（軸では右の文字）へ。-1: 逆転項目。 */
  direction: 1 | -1;
  weight: number;
  scene: Scene;
  version: number;
  /** この段階以上で出題する。 */
  tier: Tier;
  /** 軸の中の側面（FACETS のキー）。 */
  facet?: string;
  text: string;
};

type Row = [id: string, direction: 1 | -1, scene: Scene, tier: Tier, text: string, facet?: string];

function define(measure: MeasureKey, rows: Row[]): Item[] {
  return rows.map(([id, direction, scene, tier, text, facet]) => ({
    id,
    measure,
    direction,
    weight: 1,
    scene,
    version: 1,
    tier,
    ...(facet ? { facet } : {}),
    text,
  }));
}

